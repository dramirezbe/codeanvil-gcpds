"""Global methodology runtime: one uv venv shared by every project.

`~/.codeanvil-config/runtime/` holds a generated `pyproject.toml` (shipped
base from `config.yaml` plus the packages in `user.yaml`), one universal
`uv.lock` and the `.venv/`. Skill scripts run on it through `codeanvil python`.
uv failures are never swallowed: they raise `RuntimeSetupError` with uv's
stderr.
"""

import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

import yaml

from codeanvil.config.logger import get_logger
from codeanvil.config.paths import CONFIG, RUNTIME_SPEC_DIR
from codeanvil.init.system_packages import detect_system_site_packages

log = get_logger(__name__)

USER_FILE = "user.yaml"
PTH_NAME = "codeanvil-system.pth"
_IS_WIN = sys.platform == "win32"

_HEADER = """\
# Generated by `codeanvil runtime sync` — do not edit.
# Base packages come from codeanvil's config.yaml (runtime.base); add your own
# with `codeanvil runtime add <package>`, which records them in user.yaml.
"""


class RuntimeSetupError(Exception):
    """A runtime operation failed; the message says what to do."""


def _resolve(runtime_dir: Path | None) -> Path:
    """The runtime folder; read at call time so tests can point it elsewhere."""
    if runtime_dir is not None:
        return runtime_dir
    from codeanvil.config import paths
    return paths.RUNTIME_DIR


def _cfg() -> dict:
    return CONFIG.get("runtime", {})


def canonical_name(name: str) -> str:
    """PEP 503 normalised project name."""
    return re.sub(r"[-_.]+", "-", name).lower()


def requirement_name(spec: str) -> str:
    """Project name of a requirement string (`torch>=2; sys_platform...`)."""
    return canonical_name(re.split(r"[\s<>=!~;\[@(]", spec.strip(), maxsplit=1)[0])


def base_packages() -> list[str]:
    return [str(package) for package in _cfg().get("base", [])]


def render_pyproject(base: list[str], user: list[str]) -> str:
    """pyproject.toml for the runtime: base first, then user packages not in base."""
    seen: set[str] = set()
    dependencies: list[str] = []
    for spec in [*base, *user]:
        name = requirement_name(spec)
        if name in seen:
            continue
        seen.add(name)
        dependencies.append(spec)
    lines = "".join(f"    {json.dumps(spec)},\n" for spec in dependencies)
    return (
        _HEADER
        + "[project]\n"
        + 'name = "codeanvil-runtime"\n'
        + 'version = "1.0.0"\n'
        + 'requires-python = ">=3.12"\n'
        + "dependencies = [\n"
        + lines
        + "]\n\n"
        + "[tool.uv]\n"
        + "package = false\n"
    )


def load_user_packages(runtime_dir: Path | None = None) -> list[str]:
    runtime_dir = _resolve(runtime_dir)
    path = runtime_dir / USER_FILE
    if not path.is_file():
        return []
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError) as exc:
        raise RuntimeSetupError(f"cannot read {path}: {exc}") from exc
    packages = data.get("packages", []) if isinstance(data, dict) else None
    if not isinstance(packages, list):
        raise RuntimeSetupError(f"{path} must hold a 'packages:' list")
    return [str(package) for package in packages]


def save_user_packages(packages: list[str], runtime_dir: Path | None = None) -> None:
    runtime_dir = _resolve(runtime_dir)
    runtime_dir.mkdir(parents=True, exist_ok=True)
    (runtime_dir / USER_FILE).write_text(
        yaml.safe_dump({"packages": packages}, sort_keys=False), encoding="utf-8"
    )


def interpreter_path(runtime_dir: Path | None = None) -> Path:
    runtime_dir = _resolve(runtime_dir)
    if _IS_WIN:
        return runtime_dir / ".venv" / "Scripts" / "python.exe"
    return runtime_dir / ".venv" / "bin" / "python"


def site_packages(runtime_dir: Path | None = None) -> Path | None:
    runtime_dir = _resolve(runtime_dir)
    venv = runtime_dir / ".venv"
    if _IS_WIN:
        candidate = venv / "Lib" / "site-packages"
        return candidate if candidate.is_dir() else None
    hits = sorted((venv / "lib").glob("python*/site-packages"))
    return hits[-1] if hits else None


def installed_versions(runtime_dir: Path | None = None) -> dict[str, str]:
    """Canonical name -> version for every distribution in the runtime venv,
    read from the `*.dist-info` folders (no interpreter start-up)."""
    runtime_dir = _resolve(runtime_dir)
    site = site_packages(runtime_dir)
    if site is None:
        return {}
    versions: dict[str, str] = {}
    for info in site.glob("*.dist-info"):
        name, _, version = info.name[: -len(".dist-info")].partition("-")
        versions[canonical_name(name)] = version
    return versions


def missing_packages(names: list[str], runtime_dir: Path | None = None) -> list[str]:
    runtime_dir = _resolve(runtime_dir)
    installed = installed_versions(runtime_dir)
    return [name for name in names if requirement_name(name) not in installed]


def _uv() -> str:
    uv = shutil.which("uv")
    if uv is None:
        raise RuntimeSetupError("uv is not installed — install it first (https://docs.astral.sh/uv/)")
    return uv


def _run_uv(args: list[str]) -> None:
    result = subprocess.run(args, capture_output=True, text=True)
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise RuntimeSetupError(f"`{' '.join(args)}` failed (exit {result.returncode}):\n{detail}")


def write_system_pth(runtime_dir: Path | None = None) -> Path | None:
    """Bridge `runtime.system_packages` into the venv with a .pth file, which
    still applies under `python -I` (a PYTHONPATH bridge would not)."""
    runtime_dir = _resolve(runtime_dir)
    site = site_packages(runtime_dir)
    if site is None:
        raise RuntimeSetupError(f"no site-packages in {runtime_dir / '.venv'} — run codeanvil runtime sync")
    pth = site / PTH_NAME
    packages = [str(package) for package in _cfg().get("system_packages", [])]
    if not packages:
        pth.unlink(missing_ok=True)
        return None
    folders: list[str] = []
    for package in packages:
        folder = detect_system_site_packages(package)
        if folder is None:
            raise RuntimeSetupError(
                f"system package '{package}' not found — install it with your OS package manager"
            )
        if folder not in folders:
            folders.append(folder)
    pth.write_text("".join(f"{folder}\n" for folder in folders), encoding="utf-8")
    return pth


def sync(runtime_dir: Path | None = None) -> Path:
    """Write the pyproject, lock, sync the venv and bridge system packages.
    Returns the runtime interpreter path."""
    runtime_dir = _resolve(runtime_dir)
    uv = _uv()
    runtime_dir.mkdir(parents=True, exist_ok=True)
    (runtime_dir / "pyproject.toml").write_text(
        render_pyproject(base_packages(), load_user_packages(runtime_dir)), encoding="utf-8"
    )
    lock = runtime_dir / "uv.lock"
    shipped_lock = RUNTIME_SPEC_DIR / "uv.lock"
    if not lock.exists() and shipped_lock.is_file():
        shutil.copy2(shipped_lock, lock)  # shipped pins become uv's preferences
    _run_uv([uv, "lock", "--project", str(runtime_dir)])
    _run_uv([uv, "sync", "--project", str(runtime_dir), "--python", str(_cfg().get("python", "3.12"))])
    write_system_pth(runtime_dir)
    interpreter = interpreter_path(runtime_dir)
    log.info("methodology runtime ready: %s", interpreter)
    return interpreter


def add(packages: list[str], runtime_dir: Path | None = None) -> Path:
    runtime_dir = _resolve(runtime_dir)
    current = load_user_packages(runtime_dir)
    names = {requirement_name(spec) for spec in current}
    base = {requirement_name(spec) for spec in base_packages()}
    for spec in packages:
        name = requirement_name(spec)
        if name in base:
            log.info("%s is a base package of the runtime — nothing to add", name)
            continue
        if name in names:  # a new spec replaces the old one for the same project
            current = [old for old in current if requirement_name(old) != name]
        current.append(spec)
        names.add(name)
    save_user_packages(current, runtime_dir)
    return sync(runtime_dir)


def remove(packages: list[str], runtime_dir: Path | None = None) -> Path:
    runtime_dir = _resolve(runtime_dir)
    current = load_user_packages(runtime_dir)
    drop = {requirement_name(spec) for spec in packages}
    base = {requirement_name(spec) for spec in base_packages()}
    if drop & base:
        raise RuntimeSetupError(
            f"base packages of the runtime cannot be removed: {', '.join(sorted(drop & base))}"
        )
    unknown = drop - {requirement_name(spec) for spec in current}
    if unknown:
        raise RuntimeSetupError(f"not in the runtime's user packages: {', '.join(sorted(unknown))}")
    save_user_packages([spec for spec in current if requirement_name(spec) not in drop], runtime_dir)
    return sync(runtime_dir)


def listing(runtime_dir: Path | None = None) -> list[tuple[str, str, str]]:
    """(requirement, source, installed version or 'not installed')."""
    runtime_dir = _resolve(runtime_dir)
    installed = installed_versions(runtime_dir)
    rows = []
    for source, specs in (("base", base_packages()), ("user", load_user_packages(runtime_dir))):
        for spec in specs:
            rows.append((spec, source, installed.get(requirement_name(spec), "not installed")))
    return rows
